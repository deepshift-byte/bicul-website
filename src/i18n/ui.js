export const MONTHS = {
  en: ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
  lg: ["Janwali", "Febwali", "Marisi", "Apuli", "Maayi", "Juuni", "Julaayi", "Agusito", "Sebuttemba", "Okitobba", "Novemba", "Desemba"],
};

export function fmtDate(iso, lang) {
  if (!iso) return "";
  const [y, m, d] = iso.split("-").map(Number);
  return lang === "lg" ? `${d} ${MONTHS.lg[m - 1]} ${y}` : `${MONTHS.en[m - 1]} ${d}, ${y}`;
}

// Route table: one entry per page, same slug in both languages; Luganda lives under /lg
export function href(lang, path = "/") {
  const p = path.startsWith("/") ? path : "/" + path;
  if (lang === "lg") return p === "/" ? "/lg/" : "/lg" + p;
  return p;
}
